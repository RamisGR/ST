function getLang() {
  return localStorage.getItem('ct_lang') || 'ru';
}

function setLang(lang) {
  localStorage.setItem('ct_lang', lang);
  location.reload();
}

/**
 * Get translation for key.
 * Supports {0}, {1} ... substitutions via extra arguments.
 */
function t(key) {
  const lang = getLang();
  const dict = I18N[lang] || I18N['ru'];
  let str = dict[key];
  if (str === undefined) {
    // Fallback to Russian, then key itself
    str = I18N['ru'][key] || key;
  }
  for (let i = 1; i < arguments.length; i++) {
    str = str.replace('{' + (i - 1) + '}', arguments[i]);
  }
  return str;
}

/**
 * Returns HTML for the language switcher button.
 */
function renderLangSwitcher() {
  const lang = getLang();
  const flag = lang === 'ru' ? '🇷🇺' : 'EN';
  const next = lang === 'ru' ? 'en' : 'ru';
  return `<button onclick="setLang('${next}')" title="${lang === 'ru' ? 'Switch to English' : 'Переключить на русский'}"
    style="background:rgba(255,255,255,0.15); border:1px solid rgba(255,255,255,0.3); color:white;
           border-radius:20px; padding:6px 14px; font-size:1rem; cursor:pointer; font-weight:700;
           line-height:1; transition:background 0.2s;"
    onmouseover="this.style.background='rgba(255,255,255,0.25)'"
    onmouseout="this.style.background='rgba(255,255,255,0.15)'">${flag}</button>`;
}
